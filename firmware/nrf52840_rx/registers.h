#ifndef PLATINUM_REGISTERS_H
#define PLATINUM_REGISTERS_H
#include <stdint.h>

/* Register facts from Nordic's nRF52840 product specification. No vendor code. */
#define REG32(address) (*(volatile uint32_t *)(uintptr_t)(address))
#define CLOCK_BASE UINT32_C(0x40000000)
#define RADIO_BASE UINT32_C(0x40001000)
#define TIMER_BASE UINT32_C(0x4001b000) /* TIMER4 has six capture/compare registers */
#define PPI_BASE UINT32_C(0x4001f000)
#define CLOCK(offset) REG32(CLOCK_BASE + (offset))
#define RADIO(offset) REG32(RADIO_BASE + (offset))
#define TIMER(offset) REG32(TIMER_BASE + (offset))
#define PPI(offset) REG32(PPI_BASE + (offset))

enum {
    RADIO_RXEN = 0x004, RADIO_DISABLE = 0x010,
    RADIO_READY = 0x100, RADIO_ADDRESS = 0x104, RADIO_END = 0x10c,
    RADIO_DISABLED = 0x110, RADIO_RSSIEND = 0x11c,
    RADIO_CRCOK = 0x130, RADIO_CRCERROR = 0x134,
    RADIO_SHORTS = 0x200, RADIO_INTENSET = 0x304, RADIO_INTENCLR = 0x308,
    RADIO_CRCSTATUS = 0x400, RADIO_RXMATCH = 0x408, RADIO_RXCRC = 0x40c,
    RADIO_PACKETPTR = 0x504, RADIO_FREQUENCY = 0x508, RADIO_MODE = 0x510,
    RADIO_PCNF0 = 0x514, RADIO_PCNF1 = 0x518, RADIO_BASE0 = 0x51c,
    RADIO_BASE1 = 0x520, RADIO_PREFIX0 = 0x524, RADIO_PREFIX1 = 0x528,
    RADIO_RXADDRESSES = 0x530, RADIO_CRCCNF = 0x534,
    RADIO_CRCPOLY = 0x538, RADIO_CRCINIT = 0x53c,
    RADIO_RSSISAMPLE = 0x548, RADIO_STATE = 0x550,
    RADIO_MODECNF0 = 0x650, RADIO_POWER = 0xffc,
    TIMER_START = 0x000, TIMER_STOP = 0x004, TIMER_CLEAR = 0x00c,
    TIMER_CAPTURE0 = 0x040, TIMER_COMPARE0 = 0x140,
    TIMER_SHORTS = 0x200, TIMER_INTENSET = 0x304, TIMER_INTENCLR = 0x308,
    TIMER_MODE = 0x504, TIMER_BITMODE = 0x508, TIMER_PRESCALER = 0x510,
    TIMER_CC0 = 0x540,
    PPI_CHENSET = 0x504, PPI_CHENCLR = 0x508,
    PPI_CH0_EEP = 0x510, PPI_CH0_TEP = 0x514, PPI_FORK0_TEP = 0x910
};
#define TIMER_CAPTURE(n) TIMER(TIMER_CAPTURE0 + 4u * (n))
#define TIMER_COMPARE(n) TIMER(TIMER_COMPARE0 + 4u * (n))
#define TIMER_CC(n) TIMER(TIMER_CC0 + 4u * (n))
#define NVIC_ISER REG32(0xe000e100)
#define NVIC_ICER REG32(0xe000e180)
#define NVIC_ICPR REG32(0xe000e280)
#define RADIO_IRQ_MASK (UINT32_C(1) << 1)
#define TIMER_IRQ_MASK (UINT32_C(1) << 27)
#endif
